export function translateName(rawName, enabled = true) {
  if (!rawName) return "";
  // Remove file extension if present
  const extMatch = rawName.match(/\.(webm|mp4|m4v|jpg|jpeg|png|webp|zip|pdf)$/i);
  const ext = extMatch ? extMatch[0].toLowerCase() : "";
  let base = extMatch ? rawName.slice(0, -extMatch[0].length) : rawName;

  // Clean common prefixes like PP_Token_, ADMaps -, numbers
  base = base
    .replace(/^PP_Token_/i, "")
    .replace(/^ADMaps\s*-\s*/i, "")
    .replace(/[_-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();

  if (!enabled) return base;

  for (const [en, pt] of EXACT_PHRASES) {
    const regex = new RegExp(`\\b${en}\\b`, "gi");
    base = base.replace(regex, pt);
  }

  // Translate word by word
  const words = base.split(" ");
  const translatedWords = words.map((w) => {
    const clean = w.replace(/[^a-zA-Z]/g, "").toLowerCase();
    if (WORD_MAP[clean]) {
      return w.replace(/[a-zA-Z]+/, WORD_MAP[clean]);
    }
    return w;
  });

  let result = translatedWords.join(" ");

  // Highlight [Noite] / [Dia] / [Chuva]
  result = result
    .replace(/\bNoite\b/gi, "[Noite]")
    .replace(/\bDia\b/gi, "[Dia]")
    .replace(/\[\s*\[/g, "[")
    .replace(/\]\s*\]/g, "]");

  return result.trim();
}

export function isNightMap(name) {
  return /night|noite|dark|dusk|midnight|noturno/i.test(name);
}
